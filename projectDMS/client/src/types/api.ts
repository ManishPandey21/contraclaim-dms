/**
 * Notification-related types used by NotificationCenter and Enhanced API
 */
export type NotificationCategory =
  | "drafting"
  | "approvals"
  | "uploads"
  | "comments";

export interface NotificationItem {
  id: string;
  type: string;
  created_at: string;
  unread: boolean;
  resource_type?: string;
  resource_id?: string;
  category?: NotificationCategory;
  data?: {
    title?: string;
    message?: string;
    document_id?: string;
    letter_no?: string;
    subject?: string | null;
    filename?: string;
    upload_type?: string;
    job_id?: string;
    successful_count?: number;
    failed_count?: number;
    organization_id?: string;
    project_id?: string;
    [key: string]: any;
  };
  [key: string]: any;
}

export interface NotificationListResponse {
  notifications: NotificationItem[];
  total: number;
  unread_count: number;
  has_more: boolean;
}
